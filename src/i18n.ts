const dict: Record<UiLang, Record<string, string>> = { es, eu };

export function t(key: string, lang: UiLang): string {
  return dict[lang][key] ?? es[key] ?? key;
}

export function tf(key: string, lang: UiLang, vars: Record<string, string> = {}): string {
  let out = t(key, lang);
  for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(v);
  return out;
}
